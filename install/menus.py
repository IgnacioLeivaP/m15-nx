def normalize(data):
    return data[:luadis.load(data).end]

def build(name, data):
    recipe = RECIPES[name]
    original = normalize(data)
    body = HEAD % (name + '.luac')
    if recipe.get('pre'): body += recipe['pre']
    literal = '"' + ''.join('\\%03d' % b for b in original) + '"'
    body += '\nlocal original = assert(loadstring(' + literal + '))\n'
    body += 'local __port_unpack = unpack\nlocal __port_r = { original(...) }\nsetfenv(1, getfenv(original))\n'
    body += recipe.get('patch', '')
    body += '\nreturn __port_unpack(__port_r)\n'
    return body.encode('latin1').replace(b'\n', b'\r\n')
